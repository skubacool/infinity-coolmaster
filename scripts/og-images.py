"""
Draws a 1200x630 share image (Open Graph) for every built-in guide, in English
and Thai, into public/assets/og/<slug>-<locale>.jpg, and writes
src/content/articles/og.ts listing which slugs have images.

Run after adding or renaming a built-in guide:

    OG_EXPORT=og-titles.json npm run build     (Windows: set OG_EXPORT=og-titles.json && npm run build)
    python3 scripts/og-images.py og-titles.json

Needs Python 3 with Pillow built with libraqm (for Thai shaping).
Fonts come from the repository (public/fonts), so output is the same anywhere.
"""
import json
import os
import re
import sys

from PIL import Image, ImageDraw, ImageFont, features

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'public', 'assets', 'og')
LIST = os.path.join(ROOT, 'src', 'content', 'articles', 'og.ts')
W, H = 1200, 630
INK = (15, 23, 42)
MUTED = (71, 85, 105)
BLUE = (56, 189, 248)
GREEN = (16, 185, 129)
THAI = re.compile(r'[฀-๿]')


def font(kind, size):
    if kind == 'thai':
        f = ImageFont.truetype(os.path.join(ROOT, 'public/fonts/noto-sans-thai/NotoSansThai.ttf'), size,
                               layout_engine=ImageFont.Layout.RAQM)
        f.set_variation_by_name('Bold')
        return f
    return ImageFont.truetype(os.path.join(ROOT, 'public/fonts/inter/Inter-Bold.woff'), size)


def runs(text):
    """Split text into (is_thai, chunk) runs so each uses a font that has its glyphs."""
    out = []
    for ch in text:
        thai = bool(THAI.match(ch)) or (ch == ' ' and out and out[-1][0])
        if out and out[-1][0] == thai:
            out[-1][1] += ch
        else:
            out.append([thai, ch])
    return out


def width(text, size):
    return sum(font('thai' if t else 'latin', size).getlength(c) for t, c in runs(text))


def wrap(text, size, max_w):
    lines, line = [], ''
    for word in text.split(' '):
        trial = (line + ' ' + word).strip()
        if width(trial, size) <= max_w or not line:
            line = trial
        else:
            lines.append(line)
            line = word
    if line:
        lines.append(line)
    return lines


def draw_line(draw, x, y, text, size, fill):
    for thai, chunk in runs(text):
        f = font('thai' if thai else 'latin', size)
        draw.text((x, y), chunk, font=f, fill=fill)
        x += f.getlength(chunk)


def render(title, locale, path):
    img = Image.new('RGB', (W, H), 'white')
    d = ImageDraw.Draw(img)
    logo = Image.open(os.path.join(ROOT, 'public/assets/brand/logo-official.png')).convert('RGBA')
    lw = 220
    logo = logo.resize((lw, round(logo.height * lw / logo.width)), Image.LANCZOS)
    img.paste(logo, (72, 56), logo)
    kicker = 'บทความ · Cooling-as-a-Service' if locale == 'th' else 'Insights · Cooling-as-a-Service'
    draw_line(d, 72, 210, kicker, 28, GREEN)
    size = 64
    while True:
        lines = wrap(title, size, W - 144)
        if len(lines) <= 3 or size <= 44:
            break
        size -= 4
    lines = lines[:3]
    y = 262
    for line in lines:
        draw_line(d, 72, y, line, size, INK)
        y += int(size * 1.35)
    draw_line(d, 72, H - 82, 'infinitycoolmaster.com', 26, MUTED)
    for x in range(W):
        t = x / (W - 1)
        c = tuple(int(BLUE[i] + (GREEN[i] - BLUE[i]) * t) for i in range(3))
        d.line([(x, H - 18), (x, H)], fill=c)
    img.save(path, 'JPEG', quality=86, optimize=True, progressive=True)


def main():
    if not features.check('raqm'):
        sys.exit('Pillow needs libraqm for Thai text shaping.')
    titles = json.load(open(sys.argv[1], encoding='utf-8'))
    os.makedirs(OUT, exist_ok=True)
    slugs = []
    for g in titles:
        for locale in ('en', 'th'):
            render(g[locale], locale, os.path.join(OUT, f"{g['slug']}-{locale}.jpg"))
        slugs.append(g['slug'])
    with open(LIST, 'w', encoding='utf-8') as fh:
        fh.write('/** Generated by scripts/og-images.py: guides with share images. */\n')
        fh.write('export const OG_IMAGE_SLUGS: string[] = [\n')
        for s in sorted(slugs):
            fh.write(f"  '{s}',\n")
        fh.write('];\n')
    print(f'{len(slugs) * 2} images written to {OUT}')


if __name__ == '__main__':
    main()
